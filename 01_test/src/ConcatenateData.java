
public class ConcatenateData {
	public static void main(String[] args) {
		
		String fName = "John";
		char emailSymbol = '@';
		String emailExtension = "gmail.com";
		
		System.out.println("Hello " + fName + "!");
		System.out.println("Here is your email address");
		System.out.println(fName.toLowerCase() + emailSymbol + emailExtension);
	}

}
